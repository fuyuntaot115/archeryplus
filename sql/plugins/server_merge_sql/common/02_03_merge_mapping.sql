-- 说明：映射数据（WorldUID / RegionCode / WorldName / DBName）需按本次合服实际情况修改；
--       index_data_change 会 JOIN 这张表，两者在同一个 INDEX 库中执行。
-- ============================================================================
DROP TABLE IF EXISTS dbo.MergeMapping;
GO
CREATE TABLE dbo.MergeMapping
(
	[destination_world] INT NOT NULL,		-- ex) destination DB WorldUID
	[destination_region] INT NOT NULL,		-- ex) destination RegionCode
	[destination_name] NVARCHAR(50) NOT NULL,		-- ex) destination WorldName
	[destination_db] NVARCHAR(50) NOT NULL,			-- ex) destination DB Name

	[source_world] INT NOT NULL,			-- ex) source DB WorldUID
	[source_region] INT NOT NULL,			-- ex) source DB RegionCode
	[source_name] NVARCHAR(50) NOT NULL,				-- ex) source DB WorldName
	[source_db] NVARCHAR(50) NOT NULL,				-- ex) source DB Name
	CONSTRAINT [PK_MergeMapping] PRIMARY KEY ([source_world], [destination_world], [source_region], [destination_region])
);
GO

